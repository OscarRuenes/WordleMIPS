# alphabetprint.asm
# Description: Prints capital english letters from A-Z depending on the position given as $a1 argument. The position in $a1 is the top left
# 	       corner of the letter. The letters are printed in 8x8 box where each unit pixal is 8 pixel wide and 8 pixel high and the display 
#	       is 512 by 512 pixels. The color of the letters are black.
#   	       
# Input $a0: location of the top left corner of the 8x8 letter. $a0: Ascii byte to print (97-122) or -1 to print a filled 8x8 white square

.text

alphabetPrint:
	# Set the color of the pixels to be set to black
	li $s1, 0x00000000
	
	# If the argument is -1, nothing is to be printed 
	beq $a1, -1, no_character
	
	# Convert the argument passed to index of alphabet array
	addi $a1, $a1, -97
	sll $a1, $a1, 8
	la $t0, alphabets
	add $a1, $a1, $t0
	
	# Jump to label to print the char
	j character_exists
	
	# The box left alone
	no_character:
		la $a1, null
	character_exists:
	
	# Loop to look at each cell of the 8x8 space where the alpahbets are to be printed
	# If the (ith-index)*8+(jth-index) of the letter array is set to 1, the cell c in the ith row and the jth column
	# is to be set to white color. Else, leave as it is
	li $t0, 0
	print_char_row:
		
		# loop control
		slti $t2, $t0, 8
		beq $t2, 0, exit_print_char_row
		
		# Loop for each column in a row
		addi $t3, $a0, 0
		li $t1, 0
		print_char_col:
			# Loop control for inner loop
			slti $t2, $t1, 8
			beq $t2, 0, exit_print_char_col
			
			# What index to access. Shift left as the array contains words so 2 bit offset needed
			sll $t4, $t1, 2
			add $t4, $t4, $t3
			
			# Contains the row. 2 Bit offset for words and 3 bit offset as each row has 8 cells so to betget to next row, shift by 5
			sll $t7, $t0, 5
			sll $t8, $t1, 2
			
			# Load if the (ith-index)*8+(jth-index) entry is 0 or 1
			add $t8, $t8, $t7
			add $t8, $a1, $t8
			lw $t8, ($t8)
			
			# Dont print if it is not 1
			bne $t8, 1, dont_print
			
			# Set value to 0 or white color
			sw $s1, ($t4)
			dont_print:
			
			addi $t1, $t1, 1
			j print_char_col
		exit_print_char_col:
		addi $a0, $a0, 256
		
		addu $t0, $t0, 1
		
		# Repeat 8 times
		j print_char_row
	exit_print_char_row:
	
	# Jump back after update
	jr $ra
	
